/// Converts polarity corrected words (u-blox) to the transmitted words.
pub(crate) fn from_polarity_corrected(
    words: &[u32; GPS_LNAV_SUBFRAME_WORDS],
) -> [u32; GPS_LNAV_SUBFRAME_WORDS] {
    let mut ret = [0u32; GPS_LNAV_SUBFRAME_WORDS];
    let mut prev = 0u32;

    for (i, word) in words.iter().enumerate() {
        ret[i] = if prev & 0x1 > 0 {
            !word & WORD_MASK
        } else {
            word & WORD_MASK
        };

        prev = ret[i];
    }

    ret
}

/// Mirror operation of [from_polarity_corrected].
pub(crate) fn to_polarity_corrected(
    words: &[u32; GPS_LNAV_SUBFRAME_WORDS],
) -> [u32; GPS_LNAV_SUBFRAME_WORDS] {
    let mut ret = [0u32; GPS_LNAV_SUBFRAME_WORDS];
    let mut prev = 0u32;

    for (i, word) in words.iter().enumerate() {
        let word = word & WORD_MASK;

        ret[i] = if prev & 0x1 > 0 {
            !word & WORD_MASK
        } else {
            word
        };

        prev = word;
    }

    ret
}

/// u-blox words, converted back to the transmitted words.
pub(crate) fn on_air(words: [u32; GPS_LNAV_SUBFRAME_WORDS]) -> [u32; GPS_LNAV_SUBFRAME_WORDS] {
    from_polarity_corrected(&words)
}

/// Packs 10 transmitted words (30-bit, right aligned) into the 38 bytes
/// that [crate::Message::decode] expects (4 null padding bits).
pub(crate) fn words_to_bytes(
    words: &[u32; GPS_LNAV_SUBFRAME_WORDS],
) -> [u8; GPS_LNAV_SUBFRAME_BYTES] {
    let mut bytes = [0u8; GPS_LNAV_SUBFRAME_BYTES];

    for (i, word) in words.iter().enumerate() {
        write_bits(
            &mut bytes,
            i * GPS_LNAV_WORD_BITS,
            *word,
            GPS_LNAV_WORD_BITS,
        )
        .unwrap();
    }

    bytes
}

/// Mirror operation of [words_to_bytes].
pub(crate) fn bytes_to_words(bytes: &[u8]) -> [u32; GPS_LNAV_SUBFRAME_WORDS] {
    let mut words = [0u32; GPS_LNAV_SUBFRAME_WORDS];

    for (i, word) in words.iter_mut().enumerate() {
        *word = read_bits(bytes, i * GPS_LNAV_WORD_BITS, GPS_LNAV_WORD_BITS).unwrap();
    }

    words
}

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn polarity_corrected_reciprocal() {
        for frame in [UBLOX_EPH1, UBLOX_EPH2, UBLOX_EPH3] {
            assert_eq!(
                to_polarity_corrected(&from_polarity_corrected(&frame)),
                frame
            );
        }
    }

    #[test]
    fn words_bytes_reciprocal() {
        for frame in [UBLOX_EPH1, UBLOX_EPH2, UBLOX_EPH3] {
            let bytes = words_to_bytes(&frame);
            assert_eq!(bytes[GPS_LNAV_SUBFRAME_BYTES - 1] & 0x0f, 0);
            assert_eq!(bytes_to_words(&bytes), frame);
        }
    }
}
